export function uiText(value: string): string {
  if (currentLocale === 'en-US') return value
  return displayText[value] ?? value
}

export function setBlockoutLocale(locale: unknown): void {
  const next: BlockoutLocale = locale === 'en-US' ? 'en-US' : 'zh-CN'
  if (next === currentLocale) return
  currentLocale = next
  listeners.forEach((listener) => listener())
}

export function getBlockoutLocale(): BlockoutLocale {
  return currentLocale
}

export function translate(key: string, fallback = key, values?: TranslationValues): string {
  let result = messages[currentLocale][key] ?? messages['en-US'][key] ?? fallback
  if (!values) return result
  Object.entries(values).forEach(([name, value]) => {
    result = result.replaceAll(`{{${name}}}`, String(value))
  })
  return result
}

export function useBlockoutI18n(): { locale: BlockoutLocale; t: typeof translate } {
  const [, forceRender] = useState(0)
  useEffect(() => {
    const listener = (): void => forceRender((value) => value + 1)
    listeners.add(listener)
    return () => {
      listeners.delete(listener)
    }
  }, [])
  return { locale: currentLocale, t: translate }
}
